_NOKTALAMA = re.compile(r"[.,!?¿¡…:;\"“”«»()\-–—~*]+")
_SORU = re.compile(r"[?？]\s*$")
_UNLEM = re.compile(r"[!！]\s*$")


def _kucult(metin: str, dil: str) -> str:
    if dil in ("tr", "az"):
        metin = metin.replace("İ", "i").replace("I", "ı")
    metin = metin.replace("’", "'").replace("`", "'").lower().replace("̇", "")
    return metin


def normallestir(metin: str, dil: str) -> str:
    """Kucuk harf, noktalamasiz, tek bosluklu ve ust uste tekrarlari teke indirilmis hal."""
    kelimeler = _NOKTALAMA.sub(" ", _kucult(metin, dil)).split()
    for n in (3, 2, 1):                          # "merhaba merhaba" -> "merhaba", "go go go" -> "go"
        i = 0
        while i + 2 * n <= len(kelimeler):
            if kelimeler[i:i + n] == kelimeler[i + n:i + 2 * n]:
                del kelimeler[i + n:i + 2 * n]
            else:
                i += 1
    return " ".join(kelimeler)


def _dizin() -> dict[str, dict[str, int]]:
    d: dict[str, dict[str, int]] = {}
    for i, kavram in enumerate(KAVRAMLAR):
        for dil, bicimler in kavram.items():
            for b in bicimler:
                d.setdefault(dil, {}).setdefault(normallestir(b, dil), i)   # ilk eslesen kavram kazanir
    return d


_DIZIN = _dizin()


def _parca_cevir(parca: str, kaynak: str, hedef: str) -> str | None:
    anahtar = normallestir(parca, kaynak)
    i = _DIZIN.get(kaynak, {}).get(anahtar)
    if i is None or hedef not in KAVRAMLAR[i]:
        return None
    cikti = KAVRAMLAR[i][hedef][0]
    if _SORU.search(parca) and not _SORU.search(cikti):
        cikti += "?" if hedef not in ("ja", "zh") else "？"
    elif _UNLEM.search(parca) and not _UNLEM.search(cikti) and not _SORU.search(cikti):
        cikti += "!"
    return cikti


def cevir(metin: str, kaynak: str, hedef: str) -> str | None:
    """Metnin tamami (ya da virgul/nokta ile ayrilmis her parcasi) sozlukteyse ceviri, degilse None."""
    if not metin.strip() or len(metin.split()) > 8:
        return None
    parcalar = [p for p in re.split(r"(?<=[.,!?…;])\s+", metin.strip()) if p.strip()]
    sonuc = []
    for p in parcalar:
        c = _parca_cevir(p, kaynak, hedef)
        if c is None:
            return None
        if not sonuc or normallestir(c, hedef) != normallestir(sonuc[-1], hedef):   # "Tamam. Tamam." -> tek
            sonuc.append(c)
    birlesik = []
    for i, s in enumerate(sonuc):
        if i < len(sonuc) - 1 and not _SORU.search(s):
            s = s.rstrip(".!")
        if i > 0 and not _SORU.search(sonuc[i - 1]) and not re.match(r"I\b|I'", s):
            s = s[:1].lower() + s[1:]                 # virgulden sonra kucuk harf ("Hello, how are you?")
        birlesik.append(s)
    return " ".join(b if _SORU.search(b) else b + "," for b in birlesik[:-1]) + \
        (" " if len(birlesik) > 1 else "") + birlesik[-1]
